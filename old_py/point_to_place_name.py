import math
def _dist_point_to_aabb(px, py, pz, minx, miny, minz, maxx, maxy, maxz):
    """Euclidean distance from point to AABB (0 if inside)."""
    dx = 0.0
    if px < minx:
        dx = minx - px
    elif px > maxx:
        dx = px - maxx

    dy = 0.0
    if py < miny:
        dy = miny - py
    elif py > maxy:
        dy = py - maxy

    dz = 0.0
    if pz < minz:
        dz = minz - pz
    elif pz > maxz:
        dz = pz - maxz

    return math.sqrt(dx*dx + dy*dy + dz*dz)

